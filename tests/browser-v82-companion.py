from playwright.sync_api import sync_playwright
from pathlib import Path
import os
root=Path(__file__).resolve().parents[1]/'public'
css=(root/'v82-companion.css').read_text()
js=(root/'v82-companion.js').read_text()
pagehtml=(root.parent/'tests'/'fixtures'/'v82-companion-acceptance.html').read_text()
pagehtml=pagehtml.replace('<link rel="stylesheet" href="./v82-companion.css">','<style>'+css+'</style>')
pagehtml=pagehtml.replace('<script src="./v82-companion.js" defer></script>','<script>'+js+'</script>')
pagehtml=pagehtml.replace('<img src="./assets/trawellbeyond-master.svg" alt="TrawellBeyond">','<strong>TrawellBeyond</strong>')
out=Path(os.environ.get('V82_SCREENSHOT_DIR',str(root.parent/'artifacts'/'v82-browser')));out.mkdir(parents=True,exist_ok=True)
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-dev-shm-usage'])
 for width in [320,390,768,1440]:
  page=browser.new_page(viewport={'width':width,'height':850},device_scale_factor=1)
  errors=[]
  page.on('pageerror',lambda err:errors.append(str(err)))
  page.set_content(pagehtml,wait_until='load')
  assert page.locator('.tb-v82-launch').is_visible(),(width,'trigger not visible',errors)
  page.locator('.tb-v82-launch').click()
  assert page.locator('.tb-v82-panel').is_visible()
  page.screenshot(path=str(out/f'v82_companion_open_{width}.png'),full_page=False)
  assert page.locator('.tb-v82-body h3').inner_text()=='What would make this journey matter?'
  assert not page.locator('.tb-v82-panel').evaluate('(el)=>el.scrollWidth>el.clientWidth'),(width,'horizontal overflow panel')
  page.locator('.tb-v82-options button').first.click()
  page.get_by_role('button',name='Continue ↗').click()
  assert 'Who is travelling' in page.locator('.tb-v82-body h3').inner_text()
  page.locator('input[placeholder^="2 adults"]').fill('2 adults')
  page.locator('.tb-v82-body button.tb-v82-action').click()
  assert 'place or travel date' in page.locator('.tb-v82-body h3').inner_text()
  page.locator('.tb-v82-body button.tb-v82-action').click()
  assert 'Which moments' in page.locator('.tb-v82-body h3').inner_text()
  page.locator('.tb-v82-options button').first.click()
  page.locator('.tb-v82-body button.tb-v82-action').click()
  assert 'How would' in page.locator('.tb-v82-body h3').inner_text()
  page.locator('.tb-v82-body button.tb-v82-action').click()
  assert 'What kind' in page.locator('.tb-v82-body h3').inner_text()
  page.locator('.tb-v82-body button.tb-v82-action').click()
  assert 'A few places' in page.locator('.tb-v82-body h3').inner_text()
  page.wait_for_timeout(250)
  assert page.locator('.tb-v82-record').count()==2,(width,page.locator('.tb-v82-body').inner_text())
  page.locator('.tb-v82-human').click()
  assert 'personal' in page.locator('.tb-v82-body h3').inner_text()
  page.locator('input[name="name"]').fill('Test Visitor')
  page.locator('input[name="phone"]').fill('+91 9999999999')
  page.locator('input[name="consent"]').check()
  page.locator('input[name="preferredContactTime"]').fill('Evenings IST')
  page.locator('button[type="submit"]').click()
  assert page.locator('.tb-v82-ref').is_visible()
  actual=page.evaluate('window.__v82Submission')
  assert actual['source']=='companion' and actual['consent']==True and actual['purpose']=='Togetherness' and actual['preferredContactTime']=='Evenings IST',actual
  assert not errors,(width,errors)
  page.keyboard.press('Escape')
  assert page.locator('.tb-v82-panel').is_hidden()
  print(f'{width}px: PASS (dialog, progress, published recommendations, consented handoff, Escape, no overflow)')
  page.close()
 browser.close()
